from __future__ import annotations

"""
T2 Void Lensing Cross-Correlation Meter v1 — synthetic mocks experiment harness.

This module provides a lightweight grid runner around meter.run_meter for
synthetic 1D κ(x) profiles generated by the mocks backend. It is intended
as a T2-grade mock-validation harness (no real κ maps) that:

- Reads a void_lensing_meter-mocks-v1 spec;
- Builds a Cartesian grid over (backend, z_bin, R_v_bin, seed);
- For each grid cell, generates a synthetic stacked profile and measures
  wall, shoulder, and interface metrics via meter.run_meter;
- Aggregates metrics into preregistered gate inputs (R2_wall, AUROC_sh, beta_bias);
- Evaluates the prereg gates using void_lensing_meter_gates.evaluate_gates;
- Optionally writes JSON/CSV/PNG artifacts via common.io_paths.

Physics and gate thresholds are defined by
Derivation/Cosmology/Void_Lensing/T2_PROPOSAL_Void_Lensing_CrossCorrelation_Meter_v1.md
and PRE-REGISTRATION.json; this module only orchestrates synthetic runs.
"""

