DOMAIN = "cosmology/void_lensing/T2_synthetic_mocks"
# Dedicated domain for Cartesian-grid synthetic-mocks runs used in the
# extended calibration over (backend, z_bin, R_v_bin, seed).
GRID_DOMAIN = "cosmology/void_lensing/T2_synthetic_mocks_grid"


def _load_spec(path: Path) -> Dict[str, Any]:
    """Load a JSON spec file from disk."""
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def build_grid_from_spec(spec: Mapping[str, Any]) -> List[Dict[str, Any]]:
    """
    Build a small Cartesian grid of (backend, z_bin, R_v_bin, seed) values
    for the original single-backend mocks spec.
 
    In this synthetic-mocks phase we keep the grid minimal, following the
    example in the T2 proposal:
 
        backend ∈ {"PyTwinPeaks"}
        z_bin   ∈ {[0.2, 0.8]}
        R_v_bin ∈ {[10.0, 60.0]}
        seed    ∈ spec["seeds"]
    """
    parameters = spec.get("parameters", {}) or {}
    backend = str(parameters.get("backend", "PyTwinPeaks"))
    z_bin = list(parameters.get("z_bin", [0.0, 0.0]))
    R_v_bin = list(parameters.get("R_v_bin", [0.0, 0.0]))
    seeds = spec.get("seeds", []) or [0]
 
    grid: List[Dict[str, Any]] = []
    for seed in seeds:
        cell: Dict[str, Any] = {
            "backend": backend,
            "z_bin": z_bin,
            "R_v_bin": R_v_bin,
            "parameters": dict(parameters),
            "seed": int(seed),
        }
        grid.append(cell)
    return grid
 
 
def build_grid_from_spec_grid_v1(spec: Mapping[str, Any]) -> List[Dict[str, Any]]:
    """
    Build a Cartesian grid for the extended mocks-grid spec over
    (backend, z_bin, R_v_bin, seed).
 
    Expected spec shape (see specs/void_lensing_meter-mocks-grid-v1.json):
 
        {
          "parameters": {
            "backends": [...],
            "z_bins": [[z_min, z_max], ...],
            "R_v_bins": [[R_v_min, R_v_max], ...],
            ... scalar parameters ...
          },
          "seeds": [...]
        }
    """
    parameters = spec.get("parameters", {}) or {}
    backends = list(parameters.get("backends", []))
    z_bins = list(parameters.get("z_bins", []))
    R_v_bins = list(parameters.get("R_v_bins", []))
    seeds = spec.get("seeds", []) or [0]
 
    if not backends or not z_bins or not R_v_bins:
        raise ValueError(
            "Grid spec is missing one of 'backends', 'z_bins', or 'R_v_bins' axes "
            "required for building the mocks grid."
        )
 
    # Base parameter map shared across all grid cells; axis-specific keys are
    # applied per cell so that each config sees scalar backend/z_bin/R_v_bin
    # entries consistent with meter and mocks expectations.
    base_parameters: Dict[str, Any] = dict(parameters)
    for axis_key in ("backends", "z_bins", "R_v_bins"):
        base_parameters.pop(axis_key, None)
 
    grid: List[Dict[str, Any]] = []
    for backend in backends:
        for z_bin in z_bins:
            for R_v_bin in R_v_bins:
                for seed in seeds:
                    cell_params: Dict[str, Any] = dict(base_parameters)
                    cell_params["backend"] = backend
                    cell_params["z_bin"] = list(z_bin)
                    cell_params["R_v_bin"] = list(R_v_bin)
                    # Align the synthetic morphology family with the chosen backend
                    # label so that "PyTwinPeaks" and "FlagshipLike" map cleanly
                    # onto distinct profile families in mocks.generate_*.
                    cell_params.setdefault("mocks_family", backend)
 
                    cell: Dict[str, Any] = {
                        "backend": str(backend),
                        "z_bin": list(z_bin),
                        "R_v_bin": list(R_v_bin),
                        "parameters": cell_params,
                        "seed": int(seed),
                    }
                    grid.append(cell)
    return grid


def run_single(config: Mapping[str, Any]) -> Dict[str, Any]:
    """
    Run the meter once on a synthetic profile generated by the mocks backend.

    Returns a dictionary containing the config, meter metrics, and injected
    "truth" values used for ensemble-level gate metrics.
    """
    parameters = dict(config.get("parameters", {}))
    # For future extensions, a RNG could be seeded here using config["seed"].
    profile = mocks.generate_synthetic_profile_with_wall_and_shoulder(parameters)

    kappa_map = {
        "x": profile["x"],
        "kappa": profile["kappa"],
        "kappa_err": profile["kappa_err"],
    }

    metrics = meter.run_meter(
        kappa_map=kappa_map,
        void_catalog=None,
        config=dict(config),
    )

    metadata = dict(profile.get("metadata", {}))
    beta_true = float(metadata.get("beta_true", 0.0))
    beta_est = float(metrics.get("beta_interface", 0.0))

    # Work on a shallow copy so we do not mutate the meter module's internals.
    metrics = dict(metrics)
    metrics["beta_bias"] = float(abs(beta_est - beta_true))

    run_record: Dict[str, Any] = {
        "config": dict(config),
        "metrics": metrics,
        "truth": {
            "S_wall_true": float(metadata.get("S_wall_true", 0.0)),
            "beta_true": beta_true,
            "has_shoulder": bool(metadata.get("has_shoulder", True)),
        },
        "seed": int(config.get("seed", 0)),
    }
    return run_record


def aggregate_metrics_for_gates(
    all_runs: Sequence[Mapping[str, Any]],
    parameters: Mapping[str, Any],
) -> Dict[str, float]:
    """
    Aggregate per-run metrics into preregistered gate inputs.

    The synthetic-mocks stage uses simple ensemble averages:

    - R2_wall: mean of R2_wall over all runs;
    - AUROC_sh: AUROC computed from A_sh scores on a shoulder/no-shoulder
      classification toy dataset generated via mocks;
    - beta_bias: mean absolute bias |beta_interface - beta_true|.
    """
    if not all_runs:
        return {"R2_wall": 0.0, "AUROC_sh": 0.0, "beta_bias": 0.0}

    R2_vals: List[float] = []
    A_vals: List[float] = []
    beta_bias_vals: List[float] = []

    for run in all_runs:
        metrics = run.get("metrics", {})
        R2_vals.append(float(metrics.get("R2_wall", 0.0)))
        A_vals.append(float(metrics.get("A_sh", 0.0)))
        beta_bias_vals.append(float(metrics.get("beta_bias", 0.0)))

    R2_wall_mean = float(np.mean(R2_vals))
    A_sh_mean = float(np.mean(A_vals))
    beta_bias_mean = float(np.mean(beta_bias_vals))

    # Build AUROC_sh from an explicit shoulder/no-shoulder dataset.
    n_samples = int(parameters.get("auroc_n_samples", 40))
    profiles, labels = mocks.generate_shoulder_classification_dataset(n_samples, parameters)

    # Reuse a representative config (backend, z_bin, R_v_bin, parameters) but
    # drop run-specific fields such as "seed".
    base_config = dict(all_runs[0].get("config", {}))
    base_config.pop("seed", None)

    scores: List[float] = []
    for prof in profiles:
        km = {"x": prof["x"], "kappa": prof["kappa"], "kappa_err": prof["kappa_err"]}
        m = meter.run_meter(kappa_map=km, void_catalog=None, config=base_config)
        scores.append(float(m["A_sh"]))

    auroc_sh = float(mocks.compute_auroc_from_scores(scores, labels))

    gate_metrics: Dict[str, float] = {
        "R2_wall": R2_wall_mean,
        "AUROC_sh": auroc_sh,
        "beta_bias": beta_bias_mean,
        # Additional aggregated diagnostics (not directly gated).
        "A_sh": A_sh_mean,
    }
    return gate_metrics


def _flatten_run_for_csv(run: Mapping[str, Any]) -> Dict[str, Any]:
    """Flatten a single run record into a 1-row CSV-compatible dict."""
    config = run.get("config", {})
    metrics = run.get("metrics", {})
    truth = run.get("truth", {})

    z_bin = list(metrics.get("z_bin", config.get("z_bin", [0.0, 0.0])))
    R_v_bin = list(metrics.get("R_v_bin", config.get("R_v_bin", [0.0, 0.0])))
    if len(z_bin) < 2:
        z_bin = (z_bin + [0.0, 0.0])[:2]
    if len(R_v_bin) < 2:
        R_v_bin = (R_v_bin + [0.0, 0.0])[:2]

    row: Dict[str, Any] = {
        "backend": metrics.get("backend", config.get("backend", "UNKNOWN")),
        "z_bin_min": float(z_bin[0]),
        "z_bin_max": float(z_bin[1]),
        "R_v_bin_min": float(R_v_bin[0]),
        "R_v_bin_max": float(R_v_bin[1]),
        "seed": int(run.get("seed", 0)),
        "R2_wall": float(metrics.get("R2_wall", 0.0)),
        "S_wall": float(metrics.get("S_wall", 0.0)),
        "A_sh": float(metrics.get("A_sh", 0.0)),
        "AUROC_sh": float(metrics.get("AUROC_sh", 0.0)),
        "beta_interface": float(metrics.get("beta_interface", 0.0)),
        "beta_uncertainty": float(metrics.get("beta_uncertainty", 0.0)),
        "beta_bias": float(metrics.get("beta_bias", 0.0)),
        "beta_true": float(truth.get("beta_true", 0.0)),
        "SNR": float(metrics.get("SNR", 0.0)),
        "B_mode_residual": float(metrics.get("B_mode_residual", 0.0)),
        "n_voids": int(metrics.get("n_voids", 0)),
    }
    return row


def _plot_example_profile(
    run_record: Mapping[str, Any],
    parameters: Mapping[str, Any],
    fig_path: Path,
) -> None:
    """Generate a simple diagnostic plot of one synthetic profile."""
    import matplotlib.pyplot as plt

    metrics = run_record.get("metrics", {})
    profile = metrics.get("profile", {})

    x = np.asarray(profile.get("x", []), dtype=float)
    kappa = np.asarray(profile.get("kappa", []), dtype=float)
    kappa_err = np.asarray(profile.get("kappa_err", []), dtype=float)
    if x.size == 0 or kappa.size == 0:
        return

    x_wall_range = parameters.get("x_wall_range", [0.8, 1.2])
    x_bg_range = parameters.get("x_bg_range", [2.5, 4.0])

    shoulder = meter.compute_shoulder_metrics(
        x,
        kappa,
        kappa_err,
        x_wall_range=x_wall_range,
        x_bg_range=x_bg_range,
    )

    fig_path.parent.mkdir(parents=True, exist_ok=True)
    plt.figure(figsize=(6.4, 4.0))
    plt.errorbar(x, kappa, yerr=kappa_err, fmt="o", ms=3, alpha=0.8, label="κ(x)")
    plt.axvspan(x_wall_range[0], x_wall_range[1], color="#cccccc", alpha=0.3, label="wall fit region")
    plt.axvspan(x_bg_range[0], x_bg_range[1], color="#eeeeee", alpha=0.3, label="background region")

    x_sh = shoulder.get("x_sh")
    if x_sh is not None and np.isfinite(x_sh):
        plt.axvline(float(x_sh), color="C1", linestyle="--", label="shoulder")

    plt.xlabel("x = r / R_v")
    plt.ylabel("κ(x)")
    plt.title("Synthetic void-lensing profile (wall + shoulder)")
    plt.legend(loc="best", fontsize=8)
    plt.tight_layout()
    plt.savefig(fig_path, dpi=150)
    plt.close()


def _plot_grid_profiles(
    all_runs: Sequence[Mapping[str, Any]],
    parameters: Mapping[str, Any],
    fig_path: Path,
) -> None:
    """
    Overlay representative profiles from a small Cartesian grid over (backend, z_bin).

    This is intended for the mocks-grid spec, where we want a single PNG that
    shows at least one profile for each (backend, z_bin) combination.

    The actual plotting implementation lives in `Derivation/code/common/plotting`,
    to keep Matplotlib logic out of the experiment runner.
    """
    plot_void_lensing_mocks_grid_profiles(all_runs, parameters, fig_path)


def _write_artifacts(
    spec: Mapping[str, Any],
    all_runs: Sequence[Mapping[str, Any]],
    gate_metrics: Mapping[str, float],
    gate_results: Mapping[str, Any],
) -> Dict[str, str]:
    """
    Write JSON, CSV, and PNG artifacts for a completed experiment run.

    Returns a mapping of artifact labels to file-system paths.
    """
    run_name = str(spec.get("run_name", "void_lensing_meter-mocks"))
    tag = str(spec.get("tag", "void_lensing_meter-v1"))
    status = str(gate_results.get("status", "PENDING_IMPLEMENTATION"))
    failed = status != "PASSED"
 
    base_slug = io_paths.build_slug("T2_void_lensing_meter_synthetic_mocks_v1", run_name)
    base_slug = io_paths.build_slug(base_slug, tag)
 
    runs_slug = f"{base_slug}_runs"
    gates_slug = f"{base_slug}_gates"
    fig_slug = f"{base_slug}_profile"
 
    # Route artifacts for the extended Cartesian grid under a dedicated domain
    # subfolder so that they are clearly distinguishable from the original
    # single-cell PyTwinPeaks calibration.
    if run_name.endswith("-mocks-grid"):
        domain = GRID_DOMAIN
    else:
        domain = DOMAIN
 
    runs_json_path = io_paths.log_path(domain, runs_slug, failed=failed, type="json")
    gates_json_path = io_paths.log_path(domain, gates_slug, failed=failed, type="json")
    runs_csv_path = io_paths.log_path(domain, runs_slug, failed=failed, type="csv")
    fig_path = io_paths.figure_path(domain, fig_slug, failed=failed)

    spec_header = {
        "run_name": spec.get("run_name"),
        "version": spec.get("version"),
        "tag": spec.get("tag"),
        "schema_ref": spec.get("schema_ref"),
    }

    # Aggregate seeds used in this experiment for provenance receipts.
    seed_values = sorted({int(run.get("seed", 0)) for run in all_runs}) if all_runs else []

    # Package gate outcomes for provenance. This nests both scalar gate metrics and the
    # structured gate_results ledger so that downstream tooling can reconstruct the
    # exact H1–H3 verdicts.
    gate_outcomes: Dict[str, Any] = {
        "status": status,
        "gate_metrics": dict(gate_metrics),
        "gate_results": dict(gate_results),
    }

    receipts = run_receipts.build_run_receipts(
        tag=tag,
        seeds=seed_values,
        gate_outcomes=gate_outcomes,
    )

    runs_payload: Dict[str, Any] = {
        "spec": spec_header,
        "gate_metrics": dict(gate_metrics),
        "gate_results": dict(gate_results),
        "run_receipts": receipts,
        "runs": list(all_runs),
    }
    io_paths.write_log(runs_json_path, runs_payload)

    gates_payload: Dict[str, Any] = {
        "spec": spec_header,
        "gate_metrics": dict(gate_metrics),
        "gate_results": dict(gate_results),
        "run_receipts": receipts,
    }
    io_paths.write_log(gates_json_path, gates_payload)

    # If any prereg gate fails, emit an explicit CONTRADICTION report JSON routed
    # through the failed_runs/ tree. This is a lightweight, JSON-only summary that
    # records observed metrics versus thresholds and the full gate ledger.
    contradiction_path = None
    if failed:
        contradiction_slug = f"{base_slug}_contradiction"
        contradiction_path = io_paths.log_path(
            DOMAIN,
            contradiction_slug,
            failed=True,
            type="json",
        )
        contradiction_payload: Dict[str, Any] = {
            "spec": spec_header,
            "gate_metrics": dict(gate_metrics),
            "pass_fail_thresholds": {
                "R2_wall": {
                    "operator": ">=",
                    "threshold": 0.98,
                    "unit": "dimensionless",
                },
                "AUROC_sh": {
                    "operator": ">=",
                    "threshold": 0.90,
                    "unit": "dimensionless",
                },
                "beta_bias": {
                    "operator": "<=",
                    "threshold": 0.10,
                    "unit": "dimensionless",
                },
            },
            "gate_results": dict(gate_results),
            "run_receipts": receipts,
            "message": (
                "T2 Void Lensing Cross-Correlation Meter v1 synthetic-mocks "
                "calibration failed at least one prereg gate (H1–H3); see "
                "gate_results.failed_gates for details."
            ),
        }
        io_paths.write_log(contradiction_path, contradiction_payload)

    # CSV table: one row per run.
    import csv

    rows = [_flatten_run_for_csv(run) for run in all_runs]
    if rows:
        runs_csv_path.parent.mkdir(parents=True, exist_ok=True)
        with runs_csv_path.open("w", encoding="utf-8", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=sorted(rows[0].keys()))
            writer.writeheader()
            for row in rows:
                writer.writerow(row)

    # Diagnostic PNG:
    #   - For the original single-cell mocks spec, plot one representative profile.
    #   - For the mocks-grid spec, overlay representative profiles across (backend, z_bin).
    if all_runs:
        parameters_for_plot = spec.get("parameters", {}) or {}
        run_name = str(spec.get("run_name", ""))
        if run_name.endswith("-mocks-grid"):
            _plot_grid_profiles(all_runs, parameters_for_plot, fig_path)
        else:
            _plot_example_profile(all_runs[0], parameters_for_plot, fig_path)

    artifacts: Dict[str, str] = {
        "runs_json": str(runs_json_path),
        "gates_json": str(gates_json_path),
        "runs_csv": str(runs_csv_path),
        "figure": str(fig_path),
    }
    if contradiction_path is not None:
        artifacts["contradiction_json"] = str(contradiction_path)

    return artifacts


def run_experiment(spec: Mapping[str, Any], dry_run: bool = False) -> Dict[str, Any]:
    """
    Run the synthetic-mocks experiment for the original single-cell mocks spec.
 
    When dry_run=True, metrics and gates are computed in memory but no
    artifacts are written.
    """
    grid = build_grid_from_spec(spec)
    parameters = spec.get("parameters", {}) or {}
 
    all_runs: List[Dict[str, Any]] = []
    for cfg in grid:
        run_record = run_single(cfg)
        all_runs.append(run_record)
 
    gate_metrics = aggregate_metrics_for_gates(all_runs, parameters)
    gate_results = vl_gates.evaluate_gates(gate_metrics)
 
    summary: Dict[str, Any] = {
        "spec": dict(spec),
        "grid_size": len(all_runs),
        "runs": all_runs,
        "gate_metrics": gate_metrics,
        "gate_results": gate_results,
    }
 
    if not dry_run and all_runs:
        artifacts = _write_artifacts(spec, all_runs, gate_metrics, gate_results)
        summary["artifacts"] = artifacts
 
    return summary
 
 
def run_experiment_grid(spec: Mapping[str, Any], dry_run: bool = False) -> Dict[str, Any]:
    """
    Run the extended synthetic-mocks experiment over a small Cartesian grid
    in (backend, z_bin, R_v_bin, seed) as defined by the mocks-grid spec.
 
    When dry_run=True, metrics and gates are computed in memory but no
    artifacts are written.
    """
    grid = build_grid_from_spec_grid_v1(spec)
    parameters = spec.get("parameters", {}) or {}
 
    all_runs: List[Dict[str, Any]] = []
    for cfg in grid:
        run_record = run_single(cfg)
        all_runs.append(run_record)
 
    gate_metrics = aggregate_metrics_for_gates(all_runs, parameters)
    gate_results = vl_gates.evaluate_gates(gate_metrics)
 
    summary: Dict[str, Any] = {
        "spec": dict(spec),
        "grid_size": len(all_runs),
        "runs": all_runs,
        "gate_metrics": gate_metrics,
        "gate_results": gate_results,
    }
 
    if not dry_run and all_runs:
        artifacts = _write_artifacts(spec, all_runs, gate_metrics, gate_results)
        summary["artifacts"] = artifacts
 
    return summary


def _build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="T2 Void Lensing Cross-Correlation Meter v1 synthetic-mocks experiment harness.",
    )
    parser.add_argument(
        "--spec",
        type=str,
        default=None,
        help=(
            "Path to a void_lensing_meter mocks spec JSON. "
            "Defaults to the local void_lensing_meter-mocks-v1.json."
        ),
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Build grid and compute metrics/gates without writing artifacts.",
    )
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    """CLI entry point for the synthetic-mocks T2 experiment harness."""
    parser = _build_arg_parser()
    args = parser.parse_args(list(argv) if argv is not None else None)

    if args.spec is None:
        # Default to the mocks spec living alongside the meter code.
        spec_path = (
            Path(__file__).resolve().parents[1]
            / "specs"
            / "void_lensing_meter-mocks-v1.json"
        )
    else:
        spec_path = Path(args.spec).expanduser().resolve()

    if not spec_path.is_file():
        parser.error(f"--spec file not found: {spec_path}")
        return 2

    spec = _load_spec(spec_path)
    parameters = spec.get("parameters", {}) or {}

    # Enforce approval policy for artifact-writing runs before configuring IO paths.
    # This bridges the authorization DB to the IO quarantine policy by setting
    # VDM_POLICY_APPROVED=1 when the (domain, tag, script) tuple is approved.
    #
    # IMPORTANT: Approval keys are derived using the policy message
    #   f"{domain}:{script}:{tag}"
    # via [compute_expected_key](Derivation/code/common/authorization/approval.py:317).
    # For this runner, the canonical script identifier was stamped into the DB
    # using:
    #
    #   --script Derivation/code/physics/cosmology/void_lensing/experiments/T2_void_lensing_meter_synthetic_mocks_v1.py
    #
    # in approve_tag. To ensure check_tag_approval() recomputes the same key, we
    # surface this exact string through VDM_RUN_SCRIPT so that the policy sees a
    # consistent (domain, script, tag) triple.
    if not args.dry_run:
        os.environ.setdefault(
            "VDM_RUN_SCRIPT",
            "Derivation/code/physics/cosmology/void_lensing/experiments/T2_void_lensing_meter_synthetic_mocks_v1.py",
        )
        approval.check_tag_approval(
            domain="cosmology/void_lensing",
            tag="void_lensing_meter-v1",
            allow_unapproved=False,
            code_root=io_paths.DERIVATION_ROOT,
        )
        # Signal to common.io_paths._policy_quarantine that this run is approved so
        # that artifacts for PASSED gates are written outside failed_runs/.
        os.environ["VDM_POLICY_APPROVED"] = "1"
 
    # Dispatch between the original single-cell mocks spec and the extended
    # Cartesian mocks-grid spec based on the presence of grid-axis parameters
    # or the run_name suffix.
    is_grid_spec = bool(
        "backends" in parameters
        or "z_bins" in parameters
        or "R_v_bins" in parameters
        or str(spec.get("run_name", "")).endswith("-mocks-grid")
    )
 
    if is_grid_spec:
        _ = run_experiment_grid(spec, dry_run=bool(args.dry_run))
    else:
        _ = run_experiment(spec, dry_run=bool(args.dry_run))
    return 0


